SELECT 
    ni.uid,
    ni.node_location,
    ni.package_path,
    ni.root_cause_count,
    ni.package_path || '/' || CAST(ni.batch_number AS String) || '/summarize.gv' AS dir,
    ni.node_id as node_id
FROM node_info ni
WHERE EXISTS (
    SELECT 1
    FROM node_root_causes nrc
    WHERE ni.uid = nrc.uid AND nrc.root_cause_id = 'ERHeap'
) AND EXISTS (
    SELECT 1
    FROM node_root_causes nrc
    WHERE ni.uid = nrc.uid and nrc.root_cause_id = 'ERGo'
) AND ni.node_location NOT LIKE '/home/lqw/%'
AND ni.node_location NOT LIKE '<autogenerated>:%'
AND ni.node_location NOT LIKE '<nil>'
ORDER BY ni.uid
LIMIT 100