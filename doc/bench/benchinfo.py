async def fetch_repo_info_and_loc(gh: Github, fullname: str, project_root: Path) -> List[Any] | None:
    """
    异步获取单个仓库的信息和代码行数。
    将阻塞的 GitHub API 调用和 cloc 统计都转移到线程池中。
    """
    repo_name = Path(fullname).name
    
    try:
        # 1. 网络 I/O (GitHub API Calls) - 阻塞操作，使用 asyncio.to_thread
        # 我们必须把所有 PyGithub 操作都放到 to_thread 中
        def get_repo_data(gh: Github, fullname: str):
            repo = gh.get_repo(fullname)
            desc = repo.description
            topics = [topic for topic in repo.get_topics()]
            html_url = repo.html_url
            return repo, desc, topics, html_url

        repo, desc, topics, html_url = await asyncio.to_thread(get_repo_data, gh, fullname)
        
        # 2. CPU I/O (cloc statistics) - 阻塞操作，使用 asyncio.to_thread
        repo_local_path = str(project_root / repo_name)
        line_of_code = await asyncio.to_thread(get_line_of_code, repo_local_path)
        
        # 3. 构造结果
        return [
            f'[{fullname}]({html_url})', 
            desc, 
            ','.join(topics), 
            line_of_code
        ]

    except Exception as e:
        print(f"exception when getting info for {fullname}: {e}")
        return None

async def main_async():
    # 1. 初始化
    print("Loading benchmark list...")
    with open(Path("bench.yaml"), 'r') as yamlf:
        fullnames: List[str] = yaml.load(yamlf, Loader=yaml.BaseLoader)
        
    ghtoken = os.getenv("GH_TOKEN")
    if ghtoken:
        gh = Github(auth=Auth.Token(ghtoken))
    else:
        # Warning: Unauthenticated access has severe rate limits
        gh = Github()
        
    # 2. 创建所有并发任务
    tasks = []
    for fullname in fullnames:
        task = fetch_repo_info_and_loc(gh, fullname, ROOT)
        tasks.append(task)
        
    # 3. 并发执行并收集结果
    print(f"Starting concurrent fetching for {len(tasks)} repositories...")
    
    # 使用 tqdm.asyncio.tqdm_as_completed 来显示进度条
    results_async = tqdm(
        asyncio.as_completed(tasks), 
        total=len(tasks), 
        desc="Fetching Repo Data"
    )
    
    res = []
    for completed_task in results_async:
        result = await completed_task
        if result is not None:
            res.append(result)

    # 4. 结果处理
    df = pd.DataFrame(res, columns=["repo", "description", "topics", "line of code"])
    with open("bench.md", "w") as f:
        f.write("<!-- Don't Edit! Generated by benchinfo.py -->\n\n")
        f.write(df.to_markdown(index=False))
    print("✅ Benchmark data saved to bench.md")


if __name__ == '__main__':
    # 调用异步主函数
    # print(get_line_of_code(str(ROOT/"hertz"))) # 原始代码中的测试行，保留注释
    try:
        asyncio.run(main_async())
    except KeyboardInterrupt:
        print("\nProcess interrupted by user.")