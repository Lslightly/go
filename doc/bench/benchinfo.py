from tqdm import tqdm
import subprocess
load_dotenv()

if os.getenv("ROOT") is None:
    print("Please set ROOT in .env file")   
    sys.exit(1)
ROOT = Path(cast(str, os.getenv("ROOT")))

# 修正后的 get_line_of_code 函数 (如上所示)
def get_line_of_code(project_path: str) -> int:
    """
    安全地调用 cloc 并返回 Go 代码行数。
    """
    cmd = ['cloc', '--include-lang=Go', '--json', project_path]
    
    try:
        # 修正：直接传递列表 cmd，移除 shell=True
        proc = subprocess.run(cmd, capture_output=True, text=True, check=True)
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        if isinstance(e, subprocess.CalledProcessError):
            print(f"Error executing cloc (return code {e.returncode}): {e.stderr}")
        else:
            print(f"Error: Command not found: {cmd[0]}")
        return 0
    
    try:
        data = json.loads(proc.stdout)
    except json.JSONDecodeError:
        print(f"Error parsing cloc JSON output for {project_path}. Output: {proc.stdout[:100]}...")
        return 0

    if 'Go' in data:
        return cast(int, data['Go']['code'])
        
    return 0

